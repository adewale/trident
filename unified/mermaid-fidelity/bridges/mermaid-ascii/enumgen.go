//go:build ignore

// enumgen writes, for one Go package directory, a file listing every typed constant whose
// type is a named integer type declared in that package: {reflect type, value, identifier}.
// The Go compiler evaluates the values (iota included); nothing is parsed but Go source.
// The bridge injects the file with `go build -overlay`, so the package directory is untouched.
//
//	go run enumgen.go <package dir> <output file>
package main

import (
	"fmt"
	"go/ast"
	"go/build"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

var integerKinds = map[string]bool{"int": true, "int8": true, "int16": true, "int32": true, "int64": true, "uint": true,
	"uint8": true, "uint16": true, "uint32": true, "uint64": true, "uintptr": true, "byte": true, "rune": true}

func main() {
	dir, out := os.Args[1], os.Args[2]
	// The files `go build` would compile for this platform, build constraints honoured.
	bp, err := build.Default.ImportDir(dir, 0)
	if err != nil {
		panic(err)
	}
	fset := token.NewFileSet()
	name := bp.Name
	parsed := map[string]*ast.File{}
	files := append([]string{}, bp.GoFiles...)
	sort.Strings(files)
	for _, f := range files {
		file, err := parser.ParseFile(fset, filepath.Join(dir, f), nil, 0)
		if err != nil {
			panic(err)
		}
		parsed[f] = file
	}
	pkg := struct{ Files map[string]*ast.File }{parsed}

	integerTypes := map[string]bool{}
	for _, f := range files {
		for _, decl := range pkg.Files[f].Decls {
			if gen, ok := decl.(*ast.GenDecl); ok && gen.Tok == token.TYPE {
				for _, spec := range gen.Specs {
					ts := spec.(*ast.TypeSpec)
					if id, ok := ts.Type.(*ast.Ident); ok && integerKinds[id.Name] && ts.TypeParams == nil && !ts.Assign.IsValid() {
						integerTypes[ts.Name.Name] = true
					}
				}
			}
		}
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by Trident's parser bridge enumgen.go; injected with go build -overlay. DO NOT EDIT.\n\npackage %s\n\nimport \"reflect\"\n\n", name)
	b.WriteString("// TridentBridgeEnums names this package's typed integer constants by their declared identifiers.\n")
	b.WriteString("var TridentBridgeEnums = []struct {\n\tT reflect.Type\n\tV int64\n\tN string\n}{\n")
	for _, f := range files {
		for _, decl := range pkg.Files[f].Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.CONST {
				continue
			}
			current := "" // implicit repetition: a bare spec keeps the previous spec's type
			for _, spec := range gen.Specs {
				vs := spec.(*ast.ValueSpec)
				if vs.Type != nil {
					current = ""
					if id, ok := vs.Type.(*ast.Ident); ok && integerTypes[id.Name] {
						current = id.Name
					}
				} else if len(vs.Values) > 0 {
					current = ""
				}
				if current == "" {
					continue
				}
				for _, n := range vs.Names {
					if n.Name != "_" {
						fmt.Fprintf(&b, "\t{reflect.TypeOf(%s(0)), int64(%s), %q},\n", current, n.Name, n.Name)
					}
				}
			}
		}
	}
	b.WriteString("}\n")
	if err := os.WriteFile(out, []byte(b.String()), 0o644); err != nil {
		panic(err)
	}
}
